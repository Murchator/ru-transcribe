export function exercisesSystem(level, types) {
  const blocks = types
    .map(
      (t, i) => `${i + 1}. id: "${t.id}" — ${t.ru}
   Что делать: ${t.brief}`
    )
    .join("\n");

  return `Ты — преподаватель русского языка как иностранного. Уровень учеников: ${level}.

По расшифровке урока составь упражнения. Опирайся ТОЛЬКО на содержание и лексику текста.

ТИПЫ УПРАЖНЕНИЙ, которые нужно сделать:
${blocks}

ПРАВИЛА:
- Ровно 5 заданий в каждом типе.
- Каждое задание — на материале текста, а не абстрактное.
- Пропуск обозначай тремя подчёркиваниями: ___
- Задание и ответ — строго отдельно. В поле "q" НЕ должно быть ответа.
- Подбирай сложность под уровень ${level}.
- Всё по-русски.

ФОРМАТ ОТВЕТА — строго JSON:
{
  "sets": [
    {
      "type": "id типа из списка выше",
      "instruction": "инструкция для ученика одной строкой",
      "items": [
        { "q": "текст задания с ___ или вопрос", "a": "правильный ответ, или пустая строка если ответа нет" }
      ]
    }
  ]
}
Порядок наборов — как в списке выше.`;
}

/**
 * Turning a marked-up lesson picture into narration.
 *
 * The teacher's annotations are a plan for what they'll say out loud, not a
 * caption of the drawing — so the notes lead and the picture only fills gaps.
 * The output has to be comfortable to read aloud, because that's the next thing
 * that happens to it.
 */
export function composeSystemPrompt({ level, context, glossary }) {
  const glossaryBlock = glossary?.length
    ? `\n\nИМЕНА И ТЕРМИНЫ (пиши их именно так):\n${glossary.map((t) => `- ${t}`).join("\n")}`
    : "";
  const contextBlock = context?.trim() ? `\n\nО ЧЁМ УРОК: ${context.trim()}` : "";

  return `Ты — преподаватель русского языка как иностранного. Уровень ученика: ${level}.

Тебе дают изображения с урока: картинка и надписи преподавателя поверх неё. Надписи — это ПЛАН РАССКАЗА: опорные фразы, лексика, грамматические подсказки. Преподаватель будет читать твой текст вслух ученику.

ГЛАВНОЕ ПРАВИЛО: надписи — это сценарий, картинка только заполняет пробелы между ними.

ЧТО ДЕЛАТЬ:
- Иди по надписям в том порядке, в котором они расположены: сверху вниз, слева направо, следуя логике сцены.
- Используй ФОРМУЛИРОВКИ И ЛЕКСИКУ преподавателя. Если написано «Мухе плохо» — так и говори, не заменяй синонимом.
- На картинку смотри только чтобы связать надписи: кто изображён, где, что делает, что вокруг.
- Если несколько изображений — это последовательные сцены одного урока. Свяжи их в один непрерывный рассказ.
- Раскрывай служебные пометки словами. «Спаси меня! =Помоги мне!» → «Спаси меня — это значит: помоги мне».
- Варианты через косую черту тоже проговаривай: «в воде/на воде» → «муха в воде, или можно сказать — на воде».
- Если преподаватель выписал слово отдельно (например «кораблик бумажный»), введи его в рассказ и покажи, к чему оно относится.

КАК ПИСАТЬ — это устная речь, а не текст из учебника:
- Короткие предложения. Одна мысль — одно предложение.
- Разговорные связки: «итак», «вот», «значит», «смотри», «да?».
- Повторы для закрепления новой лексики — это нормально и нужно.
- Вопросы к ученику по ходу рассказа: «Почему? Потому что…».
- Уровень ${level}: подбирай грамматику и лексику соответственно.

ЧЕГО НЕ ДЕЛАТЬ:
- НЕ добавляй фактов, которых нет ни в надписях, ни на картинке.
- НЕ переводи на другие языки. Только русский.
- НЕ пиши заголовков, списков и пояснений «от автора» — только сам рассказ.

Примерно 150–350 слов на одно изображение.${contextBlock}${glossaryBlock}

ФОРМАТ ОТВЕТА — строго JSON:
{
  "text": "рассказ, абзацы через \\n\\n",
  "usedNotes": ["надписи преподавателя, которые ты использовал"],
  "unclear": ["надписи, которые не удалось разобрать — или пустой список"]
}`;
}

/**
 * Context handed to the transcription model for each chunk. Naming the setting
 * and carrying over the tail of the previous chunk both measurably reduce errors
 * at chunk seams.
 */
export function transcriptionPrompt({ context, previousTail }) {
  const parts = [
    "Запись урока русского языка. Говорит носитель русского языка, речь спокойная, монологическая.",
  ];
  if (context?.trim()) parts.push(context.trim());
  if (previousTail?.trim()) {
    parts.push(`Предыдущий фрагмент записи заканчивался так: «…${previousTail.trim()}»`);
  }
  return parts.join(" ");
}
